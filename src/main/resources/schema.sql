-- 로컬 H2 장부 테이블입니다. 기존 데이터를 지우지 않고 최초 실행 시 필요한 구조만 생성합니다.
CREATE TABLE IF NOT EXISTS expenses (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
-- 거래일은 영수증 날짜이며, 등록 시각과 다릅니다. 아직 읽지 못한 날짜는 NULL을 허용합니다.
 receipt_date VARCHAR(10), vendor VARCHAR(200) NOT NULL DEFAULT '',
 category VARCHAR(50) NOT NULL DEFAULT '미분류', description VARCHAR(500) NOT NULL DEFAULT '',
-- 금액은 원 단위 정수입니다. NULL은 미확인, 0은 실제 0원으로 구분하며 세액은 임의 계산하지 않습니다.
 amount BIGINT, supply_amount BIGINT, vat_amount BIGINT,
 payment_method VARCHAR(30) NOT NULL DEFAULT '미확인', owner_name VARCHAR(80) NOT NULL DEFAULT '',
 department VARCHAR(80) NOT NULL DEFAULT '', note VARCHAR(1000) NOT NULL DEFAULT '',
-- 새 내역은 검토 대기로 시작합니다. 확정 건만 화면의 확정 합계·엑셀·구글 전송에 포함합니다.
 status VARCHAR(20) NOT NULL DEFAULT 'REVIEW', analysis_source VARCHAR(40) NOT NULL DEFAULT 'MANUAL',
-- 분석 방식·안내·OCR 원문을 남겨 사용자가 원본과 판단 근거를 대조할 수 있게 합니다.
 analysis_message VARCHAR(2000) NOT NULL DEFAULT '', ocr_text CLOB,
-- 파일명은 증빙 폴더 기준 상대 경로입니다. 원본 해시의 유일성으로 동일 사진의 중복 등록을 막습니다.
 image_path VARCHAR(100), image_hash VARCHAR(64) UNIQUE, original_name VARCHAR(255),
-- 버전은 동시 수정 방지용입니다. 수정 요청의 기존 버전이 맞을 때만 갱신하고 1 증가시킵니다.
 created_at VARCHAR(40) NOT NULL, version INT NOT NULL DEFAULT 0
);

-- 기존 장부도 다시 만들지 않고 선택 항목을 보완합니다. 과거 내역의 승인번호는 빈칸으로 남깁니다.
ALTER TABLE expenses ADD COLUMN IF NOT EXISTS approval_number VARCHAR(40) NOT NULL DEFAULT '';
-- 과거 장부는 그대로 보존합니다. 새 선택 항목은 재인식하거나 사용자가 입력할 때 채웁니다.
ALTER TABLE expenses ADD COLUMN IF NOT EXISTS business_number VARCHAR(12) NOT NULL DEFAULT '';
ALTER TABLE expenses ADD COLUMN IF NOT EXISTS receipt_time VARCHAR(8) NOT NULL DEFAULT '';
ALTER TABLE expenses ADD COLUMN IF NOT EXISTS vendor_address VARCHAR(300) NOT NULL DEFAULT '';

-- 영수증 지출 전표입니다. 영수증을 확정하는 것과 실제 기장하는 것을 별도로 관리합니다.
-- 전표의 상호·날짜·계정·금액은 기장 당시의 사본이며, 취소해도 삭제하지 않습니다.
CREATE TABLE IF NOT EXISTS bookkeeping_entries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entry_number VARCHAR(80) NOT NULL UNIQUE,
 expense_id BIGINT NOT NULL REFERENCES expenses(id),
 active_expense_id BIGINT UNIQUE,
 expense_version INT NOT NULL,
 image_path VARCHAR(100),
 entry_date VARCHAR(10) NOT NULL, receipt_date VARCHAR(10) NOT NULL,
 vendor VARCHAR(200) NOT NULL, memo VARCHAR(500) NOT NULL,
 debit_account VARCHAR(50) NOT NULL, credit_account VARCHAR(80) NOT NULL,
 total_amount BIGINT NOT NULL CHECK (total_amount > 0),
 expense_amount BIGINT NOT NULL CHECK (expense_amount >= 0),
 vat_amount BIGINT NOT NULL CHECK (vat_amount >= 0),
 tax_mode VARCHAR(30) NOT NULL CHECK (tax_mode IN ('TOTAL_EXPENSE','SPLIT_VAT')),
 posted_by VARCHAR(80) NOT NULL, posted_at VARCHAR(40) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'POSTED' CHECK (status IN ('POSTED','CANCELLED')),
 cancelled_by VARCHAR(80) NOT NULL DEFAULT '', cancelled_at VARCHAR(40),
 cancel_reason VARCHAR(500) NOT NULL DEFAULT '',
 CHECK (expense_amount + vat_amount = total_amount),
 CHECK ((status='POSTED' AND active_expense_id IS NOT NULL AND active_expense_id=expense_id)
     OR (status='CANCELLED' AND active_expense_id IS NULL))
);
CREATE INDEX IF NOT EXISTS idx_bookkeeping_date ON bookkeeping_entries(entry_date);
CREATE INDEX IF NOT EXISTS idx_bookkeeping_expense ON bookkeeping_entries(expense_id);
-- 이미 추가 기능을 시험한 DB에도 증빙 사본 연결 열을 안전하게 보완합니다.
ALTER TABLE bookkeeping_entries ADD COLUMN IF NOT EXISTS image_path VARCHAR(100);
-- 승인번호는 기장 시 사본으로 남겨, 취소 후 원본을 수정해도 당시 값을 보존합니다.
ALTER TABLE bookkeeping_entries ADD COLUMN IF NOT EXISTS approval_number VARCHAR(40) NOT NULL DEFAULT '';
-- 취소 후 영수증을 수정하더라도 기장 당시 거래처 식별정보와 시각은 사본으로 보존합니다.
ALTER TABLE bookkeeping_entries ADD COLUMN IF NOT EXISTS business_number VARCHAR(12) NOT NULL DEFAULT '';
ALTER TABLE bookkeeping_entries ADD COLUMN IF NOT EXISTS receipt_time VARCHAR(8) NOT NULL DEFAULT '';
ALTER TABLE bookkeeping_entries ADD COLUMN IF NOT EXISTS vendor_address VARCHAR(300) NOT NULL DEFAULT '';

-- PDF 원본은 한 번만 보관하고, 각 영수증은 PDF의 특정 페이지를 가리킵니다.
CREATE TABLE IF NOT EXISTS pdf_documents (
 hash VARCHAR(64) PRIMARY KEY, original_name VARCHAR(200) NOT NULL,
 page_count INT NOT NULL CHECK (page_count BETWEEN 1 AND 20), created_at VARCHAR(40) NOT NULL
);
ALTER TABLE expenses ADD COLUMN IF NOT EXISTS pdf_hash VARCHAR(64) REFERENCES pdf_documents(hash);
ALTER TABLE expenses ADD COLUMN IF NOT EXISTS pdf_page INT;
ALTER TABLE expenses ADD COLUMN IF NOT EXISTS pdf_page_count INT;
CREATE INDEX IF NOT EXISTS idx_expenses_pdf ON expenses(pdf_hash);

-- 중복 검토는 회계 확정 상태와 별개입니다. 제외된 내역도 증빙과 판단 기록을 보존합니다.
ALTER TABLE expenses ADD COLUMN IF NOT EXISTS duplicate_state VARCHAR(20) NOT NULL DEFAULT 'NONE';
ALTER TABLE expenses ADD COLUMN IF NOT EXISTS visual_fingerprint VARCHAR(1600);
CREATE TABLE IF NOT EXISTS receipt_duplicate_matches (
 expense_id BIGINT NOT NULL REFERENCES expenses(id) ON DELETE CASCADE,
 candidate_id BIGINT NOT NULL REFERENCES expenses(id) ON DELETE CASCADE,
 signature VARCHAR(64) NOT NULL,
 reason VARCHAR(1500) NOT NULL,
 strength VARCHAR(20) NOT NULL,
 decision VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (decision IN ('PENDING','DISTINCT','EXCLUDED')),
 decided_at VARCHAR(40),
 PRIMARY KEY(expense_id,candidate_id), CHECK (expense_id > candidate_id)
);
CREATE INDEX IF NOT EXISTS idx_duplicate_candidate ON receipt_duplicate_matches(candidate_id);
-- 서로 다른 업로드 요청도 DB 커밋까지 순서를 지켜 두 번째 요청이 첫 번째 내역을 놓치지 않게 합니다.
CREATE TABLE IF NOT EXISTS receipt_duplicate_lock (id INT PRIMARY KEY CHECK (id=1));
INSERT INTO receipt_duplicate_lock(id) SELECT 1 WHERE NOT EXISTS (SELECT 1 FROM receipt_duplicate_lock WHERE id=1);
